// Package configmigration migrates supported native agent credentials into the
// agents-sandbox configuration without copying raw credentials into the VM.
package configmigration

import (
	"errors"
	"os"
)

// ErrUnsupported is returned when an agent has no safe migration provider.
var ErrUnsupported = errors.New("agent does not support safe config migration")

// ErrRerunRequired reports that the user selected native host-config
// provisioning and must rerun agents-sandbox after the config change.
var ErrRerunRequired = errors.New("configuration changed; rerun agents-sandbox")

// ErrStartDeferred reports that the user chose to review generated migration
// files before starting the sandbox.
var ErrStartDeferred = errors.New("sandbox start deferred for migration review")

// Secret is a microsandbox secret definition written to env.secret.yaml.
// Values exist only in the host-side migration plan and are never included in
// generated VM files.
type Secret struct {
	Value                 string   `yaml:"value"`
	Host                  string   `yaml:"host,omitempty"`
	Hosts                 []string `yaml:"hosts,omitempty"`
	AllowAnyHostDangerous bool     `yaml:"allow_any_host_dangerous,omitempty"`
}

// File is a host-side file generated by a migration.
type File struct {
	Path string
	Data []byte
	Mode os.FileMode
}

// Plan contains all changes needed for a safe migration. It is intentionally
// host-side: applying it does not contact or modify a VM.
type Plan struct {
	AgentName  string
	Files      []File
	Secrets    map[string]Secret
	ConfigPath string
	ConfigData []byte
	// configBaseData is the launcher config before any egress hosts were
	// added, so the network policy can be recomputed when secrets change.
	configBaseData       []byte
	SecretPath           string
	SourceHash           string
	HasNativeConfig      bool
	HasManagedConfig     bool
	AlreadyConfigured    bool
	Handled              bool
	Dismissed            bool
	Warnings             []string
	ReviewRequired       bool
	NetworkHosts         []string
	LoginProviders       []string
	LoginHosts           []string
	NetworkPath          string
	NetworkData          []byte
	NetworkAllowHosts    []string
	RequiredNetworkHosts []string
	ReviewWarnings       []string
	Retrying             bool
	SetupOnly            bool
}

// HasChanges reports whether the plan has something useful to migrate.
func (p *Plan) HasChanges() bool {
	return p != nil && (p.HasNativeConfig || p.SetupOnly) && (len(p.Files) > 0 || len(p.RequiredNetworkHosts) > 0) &&
		!p.HasManagedConfig &&
		!p.AlreadyConfigured &&
		!p.Handled &&
		!p.Dismissed
}

// HasLogin reports whether the plan needs an in-sandbox login for one or more
// providers whose credentials cannot be migrated as static secrets.
func (p *Plan) HasLogin() bool {
	return p != nil && len(p.LoginProviders) > 0
}

// NeedsAttention reports whether the plan has something the user must review,
// apply, or act on: migratable changes, a required login, or any warning.
func (p *Plan) NeedsAttention() bool {
	return p != nil && (p.HasChanges() || p.HasLogin() || len(p.Warnings) > 0 || len(p.ReviewWarnings) > 0)
}

